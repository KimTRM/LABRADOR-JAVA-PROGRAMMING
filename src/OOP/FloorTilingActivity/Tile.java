package OOP.FloorTilingActivity;

public class Tile {
    String name;
    double length;
    double width;
    double cost;

    public Tile(String name, double length, double width, double cost) {
        this.name = name;
        this.length = length;
        this.width = width;
        this.cost = cost;
    }

    // ● 1 Meter = 100 Centimeter
    // ● Area = Length x Width

}
